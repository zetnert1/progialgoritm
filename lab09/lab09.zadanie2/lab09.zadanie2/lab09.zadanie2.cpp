#include <iostream>                                          // Подключаем нужные библиотеки и пространство имён
#include <cmath>
#include <cctype>
#include <string>
using namespace std;

int digitSum(string n) {                                     // Объявляем функцию для подсчета суммы цифр числа

	int sum{ 0 };                                            // Инициализируем переменную для накопления суммы цифр

	for (char i : n) {                                       // Перебираем все цифры числа

		sum += i - '0';                                      // Добавляем значение текущей цифры к общей сумме и прибавляем 0, чтобы символ считался числом
	}
	return sum;                                              // Возвращаем сумму цифр
}

int main() {                                                 // Объявляем главную функцию

	string n{ 0 };                                           // Объявляем строковую переменную для введенного числа

	cout << "Enter your digit: ";                            // Просим пользователя ввести число
	cin >> n;                                                

	int answer = digitSum(n);                                // Вызываем функцию и сохраняем результат вычисления

	cout << "Digit summary: " << answer << endl;             // Выводим сумму цифр числа

	return 0;
}