#include <iostream>                                            // Подключаем библиотеку и пространство имён
using namespace std;

void zeroIfEven(int& value) {                                  // Объявляем функцию для обнуления четного числа

	if (value % 2 == 0) {                                      // Проверяем, является ли число четным

		value = 0;                                             // Присваиваем переменной нулевое значение
	}

}

int main() {                                                   // Объявляем главную функцию

	int value{};                                               // Инициализируем переменную
	cout << "Enter your value: ";                              // Просим пользователя ввести число
	cin >> value;                                              

	zeroIfEven(value);                                         // Вызываем функцию для проверки и изменения числа

	cout << value << endl;                                     // Выводим полученное значение
}